/** «символ», «символа», «символов» for a count. */
const chars = (n: number) => {
  const d = n % 10, h = n % 100;
  return d === 1 && h !== 11 ? "символ" : d >= 2 && d <= 4 && (h < 12 || h > 14) ? "символа" : "символов";
};

